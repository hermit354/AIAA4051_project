#!/usr/bin/env python3
"""Combine grouped Phase 1 summary CSV files.

Pipeline stage: report-table assembly after baseline evaluations.
Inputs: multiple CSV summaries generated by summarize_phase1.py.
Outputs: one merged CSV table.
Typical caller: manual report-generation workflows.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Combine grouped Phase 1 summary CSVs.")
    parser.add_argument("--input", action="append", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=Path("outputs/tables/table1_phase1_group_summary.csv"))
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rows: list[dict[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for input_path in args.input:
        for row in read_rows(input_path):
            key = (row["model"], row["group"])
            if key in seen:
                rows = [item for item in rows if (item["model"], item["group"]) != key]
            rows.append(row)
            seen.add(key)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
